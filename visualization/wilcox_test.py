import numpy as np
from scipy.stats import wilcoxon

# ==========================================
# 数据输入：同一组被试，两种方法的准确率 (%)
# 每个元素对应一个被试
# ==========================================
method_A = np.array([
    # 示例：请替换为实际数据
    # 74.65, 49.20,78.40, 51.70, 53.19, 55.42, 75.49, 69.06, 68.13 
    # 80.87, 48.13, 84.83, 55.66, 52.74, 51.88, 84.31, 73.09, 70.76 

    #73.38, 58.71, 56.94, 87.13, 72.13, 80.06, 75.00, 92.13, 85.63 
    #75.13, 58.64, 58.38, 95.69, 75.63, 83.06, 79.38, 92.69, 89.63 
    #78.38, 59.64, 54.25, 95.75, 80.69, 86.19, 75.19, 92.06, 87.63, 
    78.19, 59.93, 57.38, 95.38, 72.88, 83.13, 78.25, 91.81, 88.81,

    #60.82, 83.40, 76.36, 62.02, 70.33, 54.89, 88.11, 75.00, 76.29, 76.24, 36.78
    #68.73, 83.82, 78.71, 66.49, 73.24, 58.87, 88.31, 75.84, 78.09, 78.62, 36.78,


])

method_B = np.array([
    # 示例：请替换为实际数据
    # 79.79, 54.17, 87.15, 59.79, 56.91, 57.64, 81.01, 72.81, 72.47 

    79.19, 60.00, 56.88, 95.50, 80.63, 87.44, 78.63, 92.06, 89.81, 

    #69.38, 86.31, 82.98, 65.56, 75.07, 59.07, 92.02, 75.51, 79.51, 81.58, 36.16,

])

assert len(method_A) == len(method_B), "两组数据长度必须一致（同一组被试）"

# ==========================================
# Wilcoxon 符号秩检验（配对）
# alternative='two-sided': 双侧检验（默认）
# ==========================================
stat, p_value = wilcoxon(method_A, method_B, alternative='two-sided')

print("=" * 45)
print("       Wilcoxon Signed-Rank Test (Paired)")
print("=" * 45)
print(f"  被试数量        : {len(method_A)}")
print(f"  Method A 均值   : {np.mean(method_A):.4f} ± {np.std(method_A, ddof=1):.4f}")
print(f"  Method B 均值   : {np.mean(method_B):.4f} ± {np.std(method_B, ddof=1):.4f}")
print(f"  统计量 W        : {stat:.4f}")
print(f"  p 值            : {p_value:.4f}")
print("-" * 45)

alpha = 0.05
if p_value < alpha:
    print(f"  结论: p < {alpha}，两种方法存在显著差异 ✓")
else:
    print(f"  结论: p ≥ {alpha}，两种方法无显著差异")
print("=" * 45)
